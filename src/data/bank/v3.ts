type CardInput = Omit<QuestionCard, "categoryLabel" | "compatibleRole" | "allowDetails" | "scoringEnabled" | "comparisonEnabled"> &
  Partial<Pick<QuestionCard, "compatibleRole" | "allowDetails" | "scoringEnabled" | "comparisonEnabled">>;

const COMPLEMENTS = {
  self: "self",
  mutual: "mutual",
  giving: "receiving",
  receiving: "giving",
  watching: "being_watched",
  being_watched: "watching",
} as const;

function card(input: CardInput): QuestionCard {
  return {
    ...input,
    categoryLabel: CATEGORY_LABELS[input.categoryId] ?? input.categoryId,
    compatibleRole: input.compatibleRole ?? COMPLEMENTS[input.role],
    // Only interest cards are scored and compared unless stated otherwise.
    scoringEnabled: input.scoringEnabled ?? input.responseType === "interest",
    comparisonEnabled: input.comparisonEnabled ?? input.responseType === "interest",
    allowDetails: input.allowDetails ?? input.responseType === "interest",
  };
}

