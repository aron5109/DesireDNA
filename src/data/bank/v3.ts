import type { QuestionBank, QuestionCard } from "@/lib/quiz/bank-types";

/**
 * The curated question bank.
 *
 * Every card is written by hand with a stable semantic id of the form
 * `<category>.<topic>[_<role>]`. Ids are never reused for a different topic —
 * a changed meaning means a new id and a new bank version.
 *
 * Cards are grouped by activityId: the role variants of one activity share it,
 * which is what lets the comparison recognise complementary interests
 * (one person gives, the other receives) instead of only exact matches.
 */

